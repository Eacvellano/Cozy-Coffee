    public PanelIngredientes(Modelo.Juego juego, VistaCafe ventana) {
        this();
        conectar(ImgCafetera, "cafe", juego, ventana);
        conectar(ImgLeche, "leche", juego, ventana);
        conectar(ImgChocolate, "chocolate", juego, ventana);
        conectar(ImgAgua, "agua", juego, ventana);
        conectar(ImgAzucar, "azucar", juego, ventana);
        conectar(ImgCrema, "crema", juego, ventana);
        conectar(ImgVainilla, "vainilla", juego, ventana);
        conectar(ImgCanela, "canela", juego, ventana);
        conectar(jLabel1, "maple", juego, ventana);
        ImgMatcha.setToolTipText("Pendiente de desbloquear");
        ImgCaramelo.setToolTipText("Pendiente de desbloquear");
    }

    private void conectar(javax.swing.JLabel imagen, String ingrediente,
            Modelo.Juego juego, VistaCafe ventana) {
        imagen.setText("");
        imagen.setToolTipText(ingrediente);
        imagen.setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.HAND_CURSOR));
        imagen.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evento) {
                juego.agregarIngrediente(ingrediente);
                ventana.actualizar();
            }
        });
    }

