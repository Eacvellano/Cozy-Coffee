    public void actualizar(){
        ArrayList<String> seleccion = juego.getSeleccion();
        lbVaso.setText(seleccion.isEmpty() ? "Vaso vacía" : String.join(", ", seleccion));
        btnEntregar.setEnabled(!juego.estaPausado() && (!seleccion.isEmpty() || juego.getAtendidos() == 5));
        btnEntregar.setToolTipText(juego.getAtendidos() == 5 ? "Continuar al siguiente día" : "Entregar pedido");
    }
